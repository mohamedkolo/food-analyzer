MAX_AGE = 13


def pool_for(age, culture):
    """‏جداول الطفل للسن والثقافة دي، أو None لو مش طفل في السن ده."""
    try:
        years = float(age or 0)
    except (TypeError, ValueError):
        return None
    if not (0 < years <= MAX_AGE):
        return None
    if culture in CHILD_MEALS:
        return CHILD_MEALS[culture]
    return CHILD_MEALS["مصري"]



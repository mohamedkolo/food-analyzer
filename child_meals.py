# ‏الحاجات اللي بتتكتب بالعدد مش بالجرام، ومعاها وزن الواحدة.
# ‏portion_scale بيعرف يكبّر العدد لوحده (بيضة تبقى بيضتين)، فلازم
# النص يطلع برقم مش بجرامات.
_EACH = {"بيض": 50, "تمر": 8, "زيتون": 4}


def _text(items):
    """‏نص الوجبة زي ما بيتكتب في الجدول."""
    parts = []
    for emoji, name, food, grams in items:
        unit = _EACH.get(food)
        if unit:
            count = max(1, int(round(grams / float(unit))))
            parts.append("%s %s %d" % (emoji, name, count))
        elif food in ("حليب كامل", "حليب خالي الدسم", "لبن رايب",
                      "شوربة شعرية", "شوربة عدس", "مرق خضار"):
            parts.append("%s %s %dمل" % (emoji, name, grams))
        else:
            parts.append("%s %s %dجم" % (emoji, name, grams))
    return " + ".join(parts)


def _macros(items):
    cal = p = c = f = 0.0
    for _emoji, _name, food, grams in items:
        row = _FOOD.get(food)
        if not row:
            raise KeyError("‏صنف مش في الجدول: %s" % food)
        share = grams / 100.0
        cal += row[0] * share
        p += row[1] * share
        c += row[2] * share
        f += row[3] * share
    return (int(round(cal)), int(round(p)), int(round(c)), int(round(f)))


def _build(items):
    cal, p, c, f = _macros(items)
    return {"meal": _text(items), "cal": cal, "p": p, "c": c, "f": f,
            "child": True}



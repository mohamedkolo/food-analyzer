def tag_meal(meal_text):
    """بيرجّع dict: {مرض: 'good'/'bad'} حسب مكونات الوجبة."""
    t = str(meal_text)
    tags = {}
    for cond, rules in CONDITION_FOODS.items():
        if any(b in t for b in rules["bad"]):
            tags[cond] = "bad"
        elif any(g in t for g in rules["good"]):
            tags[cond] = "good"
    return tags


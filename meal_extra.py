def _fix_segment(seg):
    if re.search(r'\d', seg):
        return seg
    # لو الجزء إيموجي بس من غير اسم
    letters = re.sub(r'[^\u0600-\u06FFA-Za-z]', '', seg)
    if not letters:
        for emo, rep in _EMOJI_FALLBACK.items():
            if emo in seg:
                return seg.replace(emo, emo + " " + rep)
        return seg
    for kw, amt in _GRAM_RULES:
        if kw in seg:
            s = seg.rstrip()
            if s.endswith(')'):
                return s[:-1].rstrip() + f" {amt})"
            return s + f" {amt}"
    return seg

def add_grams(text):
    """بيضيف كمية لأي صنف مكتوب من غير كمية، مع الحفاظ على (kcal) لو موجودة."""
    if not isinstance(text, str):
        return text
    tail = ""
    m = re.search(r'\s*\([^)]*kcal[^)]*\)\s*$', text)
    if m:
        tail = text[m.start():]
        text = text[:m.start()]
    parts = text.split(' + ')
    return ' + '.join(_fix_segment(p) for p in parts) + tail



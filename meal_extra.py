# الدمج مع قاعدة البيانات الأصلية
# ═══════════════════════════════════════════════
def apply():
    """بيضيف الوجبات الإضافية على الموجود في meal_database (من غير ما يكرر)."""
    try:
        from meal_database import WEIGHT_LOSS, MUSCLE_GAIN, BULKING, MAINTENANCE
    except Exception as e:
        print(f"meal_extra: import error {e}")
        return

    targets = {
        "weight_loss": WEIGHT_LOSS,
        "muscle_gain": MUSCLE_GAIN,
        "bulking": BULKING,
        "maintenance": MAINTENANCE,
    }

    def _text(x):
        return x.get("meal") if isinstance(x, dict) else str(x)

    # نجمع كل القواميس اللي اسمها يبدأ بـ EXTRA (EXTRA, EXTRA2, EXTRA3 ...)
    all_extras = [v for k, v in sorted(globals().items())
                  if k.startswith("EXTRA") and isinstance(v, dict)]

    added = 0
    for source in all_extras:
        for goal, cultures in source.items():
            base = targets.get(goal)
            if base is None:
                continue
            for culture, meals_by_type in cultures.items():
                if culture not in base:
                    base[culture] = {}
                for mtype, items in meals_by_type.items():
                    base[culture].setdefault(mtype, [])
                    existing = base[culture][mtype]
                    existing_texts = {_text(x) for x in existing}
                    for it in items:
                        if _text(it) not in existing_texts:
                            existing.append(it)
                            existing_texts.add(_text(it))
                            added += 1
    # ── إضافة الجرامات لكل صنف في كل الوجبات (حتى وجبات meal_database الأصلية) ──
    try:
        for _base in (WEIGHT_LOSS, MUSCLE_GAIN, BULKING, MAINTENANCE):
            for _culture, _types in _base.items():
                for _mtype, _items in _types.items():
                    for _i, _it in enumerate(_items):
                        if isinstance(_it, dict) and "meal" in _it:
                            _it["meal"] = add_grams(_it["meal"])
                        elif isinstance(_it, str):
                            _items[_i] = add_grams(_it)
    except Exception as _e:
        print(f"meal_extra: grams pass error {_e}")

    # حقن أنظمة أكل جديدة في DIET_PLAN_TYPES (كيتو / لو-كارب)
    try:
        from meal_database import DIET_PLAN_TYPES
        for k, v in NEW_SYSTEMS.items():
            if k not in DIET_PLAN_TYPES:
                DIET_PLAN_TYPES[k] = v
    except Exception as e:
        print(f"meal_extra: systems error {e}")

    # النظام الكيميائي — مدخله متعرّف في chemical_diet عشان يبقى مصدر واحد
    # للأيام والمدخل مع بعض. try مستقل عشان فشله ما يوقّعش حقن الأنظمة اللي فوق.
    try:
        from meal_database import DIET_PLAN_TYPES
        from chemical_diet import CHEMICAL_SYSTEM
        DIET_PLAN_TYPES.setdefault("chemical", CHEMICAL_SYSTEM)
    except Exception as e:
        print(f"meal_extra: chemical system error {e}")

    try:
        from sleeve_diet import SLEEVE_SYSTEM
        DIET_PLAN_TYPES.setdefault("sleeve", SLEEVE_SYSTEM)
    except Exception as e:
        print(f"meal_extra: sleeve system error {e}")

    print(f"meal_extra: added {added} extra meals")
    return added


